/**
 * Interface translations.
 *
 * Four locales, one flat key space, plain objects. There is no i18n library
 * behind this on purpose: the app has no plural rules to speak of, formats its
 * one date by hand in UTC, and had already lost a page to a hydration mismatch
 * once — a translation layer whose behaviour I can read in full is worth more
 * here than one with features this product does not use.
 *
 * What is *not* translated: Handbook fields, official Monash page text, and
 * anything a student wrote. Those are quotations from a source, and translating
 * a quotation silently is how a platform ends up asserting something the
 * official page never said. The chrome around them changes language; the
 * evidence does not.
 */
export type LocaleCode = 'en' | 'zh' | 'ja' | 'ko'

export interface LocaleOption {
  code: LocaleCode
  /** Written in its own language — a switcher is useless in a language you cannot read. */
  label: string
  /** For the <html lang> attribute. */
  htmlLang: string
}

