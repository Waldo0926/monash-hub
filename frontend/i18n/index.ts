export const MESSAGES: Record<LocaleCode, Messages> = { en, zh, ja, ko }

/**
 * Look up a key, substituting ``{name}`` placeholders.
 *
 * A missing translation falls back to English rather than rendering the key: a
 * half-translated page reads badly, but a page showing ``units.title`` reads as
 * broken.
 */
export function translate(
  locale: LocaleCode,
  key: string,
  params?: Record<string, string | number>
): string {
  const template = MESSAGES[locale]?.[key] ?? MESSAGES[DEFAULT_LOCALE][key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole
  )
}

/** Best matching supported locale for an ``Accept-Language`` header. */
export function matchLocale(header: string | undefined | null): LocaleCode | null {
  if (!header) return null
  for (const part of header.split(',')) {
    const tag = part.split(';')[0]!.trim().toLowerCase()
    if (!tag) continue
    if (tag.startsWith('zh')) return 'zh'
    if (tag.startsWith('ja')) return 'ja'
    if (tag.startsWith('ko')) return 'ko'
    if (tag.startsWith('en')) return 'en'
  }
  return null
}

export function isLocale(value: unknown): value is LocaleCode {
  return typeof value === 'string' && LOCALES.some(l => l.code === value)
}
